'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'dist', 'Harness Hub');
if (process.platform !== 'win32') throw new Error('此构建脚本用于 Windows 桌面端。');
execFileSync('go', ['build', '-o', 'serve.exe', './cmd/serve'], { cwd: path.join(root, 'server-go'), stdio: 'inherit', windowsHide: true });
fs.mkdirSync(output, { recursive: true });
fs.cpSync(path.dirname(require('electron')), output, { recursive: true });
fs.renameSync(path.join(output, 'electron.exe'), path.join(output, 'Harness Hub.exe'));
const appDir = path.join(output, 'resources', 'app');
fs.mkdirSync(appDir, { recursive: true });
for (const file of ['main.js', 'backend.js']) fs.copyFileSync(path.join(root, 'desktop', file), path.join(appDir, file));
fs.writeFileSync(path.join(appDir, 'package.json'), JSON.stringify({ name: 'harness-hub-desktop', version: '1.0.0', main: 'main.js' }));
fs.writeFileSync(path.join(output, 'resources', 'workspace.json'), JSON.stringify({ root }));
const png = fs.readFileSync(path.join(root, 'public', 'icon-192.png'));
const ico = Buffer.alloc(22); ico.writeUInt16LE(1, 2); ico.writeUInt16LE(1, 4);
ico[6] = ico[7] = 192; ico.writeUInt16LE(1, 10); ico.writeUInt16LE(32, 12);
ico.writeUInt32LE(png.length, 14); ico.writeUInt32LE(22, 18);
fs.writeFileSync(path.join(output, 'Harness Hub.ico'), Buffer.concat([ico, png]));
console.log('桌面端已构建：' + path.join(output, 'Harness Hub.exe'));
console.log('此本机桌面版连接当前项目：' + root);
